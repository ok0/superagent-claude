/** AI attribution: the shared line rule strips agent output; check-commits rejects a superset of what it removes. */
import { describe, expect, it } from 'vitest'
import { checkMessage } from '../scripts/check-commits.ts'
import { isAiAttributionLine, stripAiAttribution } from '../src/infra/text.ts'

const PRODUCT = ['Claude', 'Code'].join(' ')
const AI = 'Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>'
const GEN = '🤖 Generated with [' + PRODUCT + '](https://claude.com/claude-code)'
const JANE = 'Co-authored-by: Jane Doe <jane@example.com>'

describe('stripAiAttribution', () => {
  it('removes the AI co-author trailer and the generated line and keeps a human co-author', () => {
    expect(stripAiAttribution('feat: x\n\nBody text.\n\n' + GEN + '\n\n' + AI + '\n' + JANE + '\n')).toBe(
      'feat: x\n\nBody text.\n\n' + JANE + '\n',
    )
  })

  it('matches case-insensitively', () => {
    expect(stripAiAttribution('fix: y\n\nco-authored-by: claude <bot@anthropic.com>\n')).toBe('fix: y\n')
    expect(stripAiAttribution('fix: y\n\nCO-AUTHORED-BY: Helper <x@ANTHROPIC.COM>')).toBe('fix: y')
  })

  it('removes only the attribution and trailing blank lines', () => {
    expect(stripAiAttribution('Summary\n\n' + GEN)).toBe('Summary')
  })

  it('returns attribution-only text as empty', () => {
    expect(stripAiAttribution(GEN + '\n\n' + AI)).toBe('')
  })

  it.each([
    'feat: x',
    'feat: x\n\n' + JANE + '\n',
    'Ask Claude about the parser.\nClaude said it is fine.',
    'Co-authored-by: Claudette Roy <c@example.com>',
    'Generated with care.',
    'a\n\n\nb\n\n',
    'line\r\nnext\r\n',
  ])('leaves %j unchanged', input => {
    expect(stripAiAttribution(input)).toBe(input)
  })
})

describe('check-commits and strip agree', () => {
  const SHARED: [string, boolean][] = [
    [AI, true],
    ['co-authored-by: claude <a@b.c>', true],
    ['Co-authored-by: Bot <bot@anthropic.com>', true],
    [GEN, true],
    ['Generated with Claude', true],
    ['generated with the help of claude', true],
    [JANE, false],
    ['Ask Claude about it', false],
    ['Co-authored-by: Claudette Roy <c@example.com>', false],
    ['Generated with care', false],
  ]

  it.each(SHARED)('%j: rejected by check-commits iff stripped (%s)', (line, expected) => {
    const message = 'fix: x\n\n' + line
    const rejected = checkMessage(message).some(reason => reason.includes('attribution'))
    const stripped = stripAiAttribution(message) !== message
    expect(rejected).toBe(expected)
    expect(stripped).toBe(expected)
  })

  it('isAiAttributionLine is the shared check-commits rule', () => {
    for (const [line, expected] of SHARED)
      expect(('fix: x\n\n' + line).split('\n').some(isAiAttributionLine)).toBe(expected)
  })

  const BROADER_ONLY = [
    'Generated by Claude',
    'See https://claude.ai/code/x',
    'Reply to noreply@anthropic.com',
    'Co-authored-by: Anthropic Bot <bot@example.com>',
  ].map(line => 'fix: x\n\n' + line)

  it.each(BROADER_ONLY)('check-commits still rejects %j, which strip leaves unchanged', message => {
    expect(checkMessage(message).some(reason => reason.includes('attribution'))).toBe(true)
    expect(stripAiAttribution(message)).toBe(message)
  })
})
